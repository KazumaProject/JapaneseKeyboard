    @Test fun ambiguousStrokeWaitsForChoiceAndNextStrokeDismissesOldChoices() {
        val path = GesturePresets.path("0,0 10,10 20,0")
        val set = GestureSet("ambiguous", "Ambiguous", listOf("a", "b").map { GestureEntry(it, GestureOutput.LiteralText(it), listOf(path)) })
        withView(set) { view ->
            val output = mutableListOf<GestureOutput>()
            view.onOutput = { output.add(it); true }
            draw(view, "20,20 100,100 180,20")
            await { buttons(view).any { it.contentDescription == "Match: b" } }
            assertTrue(output.isEmpty())
            buttons(view).single { it.contentDescription == "Match: b" }.performClick()
            assertEquals(listOf(GestureOutput.LiteralText("b")), output)
            draw(view, "20,20 100,100 180,20")
            await { buttons(view).any { it.contentDescription == "Match: a" } }
            val stale = buttons(view).single { it.contentDescription == "Match: a" }
            view.handlePadAction(KeyAction.SwitchDirectMode)
            stale.performClick()
            assertEquals(1, output.size)
            assertFalse(buttons(view).any { it.contentDescription?.startsWith("Match:") == true })
        }
    }
    @Test fun tapPunctuationShiftAndDeferredCommandsUseTheSameInputOrder() {
        withView(PalmGesturePresets.sets(false).first()) { view ->
            val queue = mutableListOf<() -> GestureOutput?>()
            view.onResolveOutput = { queue.add(it) }
            tap(view); tap(view)
            await { queue.size == 2 }
            assertNull(queue.removeAt(0).invoke())
            assertEquals(GestureOutput.LiteralText("."), queue.removeAt(0).invoke())
            draw(view, "100,180 100,20") // Shift.
            draw(view, "20,180 100,20 164,180") // a, before the queued Shift executes.
            await { queue.size == 2 }
            val shift = queue.removeAt(0).invoke() as GestureOutput.Command
            assertEquals(KeyAction.ShiftKey, shift.action)
            view.handlePadAction(shift.action)
            assertEquals(GestureOutput.LiteralText("A"), queue.removeAt(0).invoke())
            assertFalse(view.session.activePad().shift)
            tap(view)
            await { queue.isNotEmpty() }; assertNull(queue.removeAt(0).invoke())
            draw(view, "20,100 180,100")
            await { queue.isNotEmpty() }; assertEquals(GestureOutput.LiteralText("-"), queue.removeAt(0).invoke())
        }
    }
    @Test fun guideMenuRemainsFullyVisibleAtTheMinimumKeyboardHeight() {
        withView(PalmGesturePresets.sets(false).first()) { view ->
            view.measure(View.MeasureSpec.makeMeasureSpec(300, View.MeasureSpec.EXACTLY), View.MeasureSpec.makeMeasureSpec(240, View.MeasureSpec.EXACTLY))
            view.layout(0, 0, 300, 240)
            val menu = view.findViewById<Button>(R.id.gesture_menu)
            val visible = android.graphics.Rect()
            assertTrue(menu.getLocalVisibleRect(visible))
            assertEquals(menu.height, visible.height())
        }
    }
    @Test fun rejectedStrokesNeverOfferUnrelatedCandidates() {
        val matcher = GestureRecognizer.Prepared(PalmGesturePresets.sets(false).first())
        assertEquals(GestureRecognizer.Decision.Rejected, matcher.evaluate(emptyList()))
        assertEquals(GestureRecognizer.Decision.Rejected,
            matcher.evaluate(GesturePresets.path("0,0 10,0 0,0 10,0 0,0 10,0")))
    }
    @Test fun cancellationInvalidatesQueuedOutputAndClearsOneShotShift() {
        withView(PalmGesturePresets.sets(false).first()) { view ->
            val queue = mutableListOf<() -> GestureOutput?>()
            view.onResolveOutput = { queue.add(it) }
            view.handlePadAction(KeyAction.ShiftKey)
            tap(view); await { queue.isNotEmpty() }
            view.cancelInput()
            assertNull(queue.single().invoke())
            assertFalse(view.session.activePad().shift)
        }
    }
