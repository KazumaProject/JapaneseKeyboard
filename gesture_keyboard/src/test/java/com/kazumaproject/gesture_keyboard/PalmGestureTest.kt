    private fun await(condition: () -> Boolean) {
        val end = System.nanoTime() + 5_000_000_000L
        while (!condition() && System.nanoTime() < end) { shadowOf(Looper.getMainLooper()).idle(); Thread.sleep(10) }
        assertTrue("Timed out waiting for recognition", condition())
    }
    private fun buttons(view: View): List<Button> = (if (view is Button) listOf(view) else emptyList()) +
        if (view is ViewGroup) (0 until view.childCount).flatMap { buttons(view.getChildAt(it)) } else emptyList()
    private fun withView(set: GestureSet, run: (GestureKeyboardView) -> Unit) {
        val controller = Robolectric.buildActivity(Activity::class.java).setup().visible()
        try {
            val view = GestureKeyboardView(controller.get())
            view.configure(listOf(set), GestureSessionState().withSet("pad_1", set.id).withSet("pad_2", set.id), GestureControlLayout())
            controller.get().setContentView(view)
            view.measure(View.MeasureSpec.makeMeasureSpec(1000, View.MeasureSpec.EXACTLY), View.MeasureSpec.makeMeasureSpec(700, View.MeasureSpec.EXACTLY))
            view.layout(0, 0, 1000, 700)
            run(view)
        } finally { controller.pause().stop().destroy() }
    }
    private fun tap(view: GestureKeyboardView) {
        val pad = view.leftPad
        for (action in listOf(MotionEvent.ACTION_DOWN, MotionEvent.ACTION_UP)) {
            MotionEvent.obtain(0, 100, action, pad.width / 2f, pad.height / 2f, 0).also { pad.dispatchTouchEvent(it); it.recycle() }
        }
    }
    private fun draw(view: GestureKeyboardView, path: String) {
        val source = GesturePresets.path(path)
        val scale = minOf(view.leftPad.width, view.leftPad.height) * .7f /
            maxOf(source.maxOf { it.x } - source.minOf { it.x }, source.maxOf { it.y } - source.minOf { it.y })
        val cx = (source.maxOf { it.x } + source.minOf { it.x }) / 2
        val cy = (source.maxOf { it.y } + source.minOf { it.y }) / 2
        val points = source.map { GesturePoint((it.x - cx) * scale + view.leftPad.width / 2f, (it.y - cy) * scale + view.leftPad.height / 2f) }
        points.forEachIndexed { i, point -> MotionEvent.obtain(0, 100,
            if (i == 0) MotionEvent.ACTION_DOWN else MotionEvent.ACTION_MOVE, point.x, point.y, 0)
            .also { view.leftPad.dispatchTouchEvent(it); it.recycle() } }
        MotionEvent.obtain(0, 100, MotionEvent.ACTION_UP, points.last().x, points.last().y, 0)
            .also { view.leftPad.dispatchTouchEvent(it); it.recycle() }
    }
    @Test fun allAlternateFormsKeepTheirOutputAndSmallTiltDoesNotLoseDirection() {
        (PalmGesturePresets.sets(false) + PalmGesturePresets.punctuation).forEach { set ->
            set.validate()
            val matcher = GestureRecognizer.Prepared(set)
            set.entries.forEach { entry -> entry.samples.forEach { sample ->
                val angle = Math.toRadians(7.0)
                val drawn = sample.map { GesturePoint((it.x * kotlin.math.cos(angle) - it.y * kotlin.math.sin(angle)).toFloat() * 20 + 123,
                    (it.x * kotlin.math.sin(angle) + it.y * kotlin.math.cos(angle)).toFloat() * 20 + 73) }
                assertEquals("${set.id}/${entry.id}", entry.output, matcher.recognize(drawn)?.entry?.output)
            } }
        }
    }
